/** The Shapes gallery: every Excel section, with the shapes the host draws enabled. */
export const MAC_SHAPE_GALLERY: readonly MacRibbonMenuItem[] = SECTIONS.flatMap((group) => [
  {
    id: `mac.insert.heading.shape.${group.key}`,
    label: group.en,
    labelJa: group.ja,
    heading: true,
    own: true,
  },
  ...group.rows.map(([ja, en, id, icon], index): MacRibbonMenuItem => {
    const supported = id !== undefined;
    return {
      id: id ?? `mac.insert.shape.${group.key}.${index}`,
      label: en,
      labelJa: ja,
      own: true,
      ...(icon ? { icon } : {}),
      disabled: !supported,
      disabledReason: supported ? undefined : NOT_IMPLEMENTED.en,
    };
  }),
]);
