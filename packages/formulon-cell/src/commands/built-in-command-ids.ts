const BUILT_IN_COMMAND_ID_SET: ReadonlySet<string> = new Set(BUILT_IN_COMMAND_IDS);

/** True when `id` names a built-in UI command. */
export const isBuiltInCommandId = (id: string): id is BuiltInCommandId =>
  BUILT_IN_COMMAND_ID_SET.has(id);
