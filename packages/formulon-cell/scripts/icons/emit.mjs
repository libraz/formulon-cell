/**
 * Pure helpers for the icon generator: spec hashing, the generated TS module, CSS data URIs
 * and their markers, the staleness check, and the house rules layered on gridsmith's lint.
 * Nothing here imports gridsmith, so the unit suite and `generate.mjs --check` run without it.
 */

import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

export const MODULE_PATH = 'src/toolbar/ribbon-icons.generated.ts';

/** Group whose icons exist only as CSS data URIs; never part of the JS registry. */
export const CSS_GROUP = 'css';

export const sha256 = (text) => createHash('sha256').update(text).digest('hex');

const sortKeys = (value) => {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortKeys(value[key])]),
    );
  }
  return value;
};

/** Canonical JSON of a spec: keys sorted recursively, so formatting never moves the hash. */
export const normalizeSpec = (spec) => JSON.stringify(sortKeys(spec));

export const specHash = (spec) => sha256(normalizeSpec(spec));

export const uriKey = (name, consumer, theme) => `${name}@${consumer}#${theme}`;

/** gridsmith segments to the registry's segment shape (string widths, no stray fill). */
export const toIconSegments = (segments) =>
  segments.map((segment) => {
    if (segment.fill !== undefined) {
      return { d: segment.d, fill: segment.fill, fillRule: segment.fillRule };
    }
    const out = {
      d: segment.d,
      stroke: segment.stroke,
      strokeWidth: String(segment.strokeWidth),
      strokeLinecap: segment.strokeLinecap,
      strokeLinejoin: segment.strokeLinejoin,
    };
    if (segment.strokeDasharray) out.strokeDasharray = segment.strokeDasharray;
    return out;
  });

const tsString = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const tsKey = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : tsString(name));

const SEGMENT_FIELDS = [
  'd',
  'fill',
  'fillRule',
  'stroke',
  'strokeWidth',
  'strokeLinecap',
  'strokeLinejoin',
  'strokeDasharray',
];

const emitSegment = (segment) =>
  `{ ${SEGMENT_FIELDS.filter((field) => segment[field] !== undefined)
    .map((field) => `${field}: ${tsString(String(segment[field]))}`)
    .join(', ')} }`;

/** The generated registry module. `icons` maps a registry name to its IconSegment list. */
export const emitModule = ({ palette, icons }) => {
  const names = Object.keys(icons).sort();
  const paletteLines = Object.entries(palette).map(([role, hex]) => `  ${role}: '${hex}',`);
  const union =
    names.length === 0 ? ' never;' : `\n${names.map((n) => `  | ${tsString(n)}`).join('\n')};`;
  const body = names.map(
    (name) =>
      `  ${tsKey(name)}: [\n${icons[name].map((s) => `    ${emitSegment(s)},`).join('\n')}\n  ],`,
  );
  return [
    '// Generated by scripts/icons/generate.mjs from icons/specs. Do not edit.',
    "import type { IconDefinition } from './icon-types.js';",
    '',
    'export const ICON_PALETTE = {',
    ...paletteLines,
    '} as const;',
    '',
    `export type RibbonIconName =${union}`,
    '',
    body.length === 0
      ? 'export const RIBBON_ICONS: Readonly<Record<RibbonIconName, IconDefinition>> = {};'
      : `export const RIBBON_ICONS: Readonly<Record<RibbonIconName, IconDefinition>> = {\n${body.join('\n')}\n};`,
    '',
  ].join('\n');
};

const roleOf = (palette) => Object.fromEntries(Object.entries(palette).map(([r, h]) => [h, r]));

const encodeUri = (text) =>
  text.replace(
    /[<>#"%]/g,
    (c) => `%${c.charCodeAt(0).toString(16).toUpperCase().padStart(2, '0')}`,
  );

/** CSS `url("data:…")` of an icon with the theme's values baked into the themed roles. */
export const dataUriFor = (segments, tokens, theme) => {
  const roles = roleOf(tokens.palette);
  const themed = tokens.themes[theme] ?? {};
  const color = (hex) => {
    const role = roles[hex];
    return role !== undefined && themed[role] !== undefined ? themed[role] : hex;
  };
  const paths = segments.map((s) => {
    const parts = [`d='${s.d}'`];
    if (s.fill !== undefined) {
      parts.push(`fill='${color(s.fill)}'`);
      if (s.fillRule) parts.push(`fill-rule='${s.fillRule}'`);
    } else {
      parts.push("fill='none'", `stroke='${color(s.stroke)}'`, `stroke-width='${s.strokeWidth}'`);
      if (s.strokeLinecap) parts.push(`stroke-linecap='${s.strokeLinecap}'`);
      if (s.strokeLinejoin) parts.push(`stroke-linejoin='${s.strokeLinejoin}'`);
      if (s.strokeDasharray) parts.push(`stroke-dasharray='${s.strokeDasharray}'`);
    }
    return `<path ${parts.join(' ')}/>`;
  });
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'>${paths.join('')}</svg>`;
  return `url("data:image/svg+xml,${encodeUri(svg)}")`;
};

const URI_RE =
  /url\(\s*(?:"data:image\/svg[^"]*"|'data:image\/svg[^']*'|data:image\/svg[^)]*)\s*\)/g;
const MARKER_RE = /\/\*\s*(icon-exempt:[^*]*?|icon:[^*]*?)\s*\*\//y;
const ICON_MARKER = /^icon:([A-Za-z0-9_-]+) @([A-Za-z0-9_-]+)(?: theme=(ink))?$/;
const MASK_PROPERTY = /^(?:-webkit-)?mask(?:-image)?$/;

const lineOf = (text, index) => text.slice(0, index).split('\n').length;

const propertyAt = (css, index) => {
  const before = css.slice(0, index);
  const start = Math.max(before.lastIndexOf(';'), before.lastIndexOf('{'), before.lastIndexOf('}'));
  return /^\s*([-\w]+)\s*:/.exec(before.slice(start + 1))?.[1] ?? '';
};

/**
 * Every `data:image/svg` URI in a stylesheet with its marker.
 * kind is `icon` (marked, grammar ok), `exempt`, or `bare` (no marker).
 */
export const parseCssUris = (css, tokens) => {
  const uris = [];
  const errors = [];
  for (const match of css.matchAll(URI_RE)) {
    const start = match.index;
    const end = start + match[0].length;
    const line = lineOf(css, start);
    let cursor = end;
    while (/\s/.test(css[cursor] ?? '')) cursor += 1;
    MARKER_RE.lastIndex = cursor;
    const marker = MARKER_RE.exec(css);
    const entry = { kind: 'bare', uri: match[0], start, end, line };
    if (marker) {
      const body = marker[1];
      if (body.startsWith('icon-exempt:')) {
        entry.kind = 'exempt';
      } else {
        const parsed = ICON_MARKER.exec(body);
        let after = cursor + marker[0].length;
        while (/\s/.test(css[after] ?? '')) after += 1;
        if (!parsed) {
          errors.push(`line ${line}: malformed marker "${body}"`);
          entry.kind = 'invalid';
        } else if (css[after] !== ';') {
          errors.push(`line ${line}: marker "${body}" must be followed by ';'`);
          entry.kind = 'invalid';
        } else {
          entry.kind = 'icon';
          entry.name = parsed[1];
          entry.consumer = parsed[2];
          entry.theme = parsed[3] ?? 'light';
          if (!(entry.consumer in (tokens.cssConsumers ?? {}))) {
            errors.push(`line ${line}: ${entry.name} uses unknown consumer @${entry.consumer}`);
          }
          if (MASK_PROPERTY.test(propertyAt(css, start))) {
            errors.push(`line ${line}: ${entry.name} is inside a mask value; use background-image`);
          }
        }
      }
    }
    uris.push(entry);
  }
  return { uris, errors };
};

/** Replace the URI of every marked entry with `resolve(name, consumer, theme)`; null keeps it. */
export const rewriteCssUris = (css, tokens, resolve) => {
  const { uris } = parseCssUris(css, tokens);
  let out = css;
  for (const entry of uris.filter((u) => u.kind === 'icon').reverse()) {
    const next = resolve(entry.name, entry.consumer, entry.theme);
    if (next !== null) out = out.slice(0, entry.start) + next + out.slice(entry.end);
  }
  return out;
};

/** The pinned commit of gridsmith recorded in yarn.lock, or null when the entry is absent. */
export const yarnLockGridsmithCommit = (text) => {
  for (const block of text.split(/\n\n+/)) {
    if (!block.trimStart().startsWith('"@libraz/gridsmith@')) continue;
    return /resolution:.*#commit=([0-9a-f]{40})/.exec(block)?.[1] ?? null;
  }
  return null;
};

const sameSet = (a, b) => a.length === b.length && a.every((x, i) => x === b[i]);

/**
 * Staleness check over data already read from disk: spec hashes, the generated module and every
 * marked CSS URI against the lock, plus unmarked URIs. Pure, so tests can mutate each input.
 */
export const checkTree = ({ tokens, lock, specs, moduleText, css }) => {
  const errors = [];
  const names = Object.keys(specs).sort();
  const locked = Object.keys(lock.specs).sort();
  for (const name of names) {
    const entry = lock.specs[name];
    if (!entry) errors.push(`spec ${name} is not in the lock; run yarn icons:generate`);
    else if (entry.group !== specs[name].group) errors.push(`spec ${name} moved group`);
    else if (entry.sha256 !== specHash(specs[name].spec)) {
      errors.push(`spec ${name} changed since the lock; run yarn icons:generate`);
    }
  }
  for (const name of locked) {
    if (!specs[name]) errors.push(`lock lists ${name} but its spec file is gone`);
  }
  const cssNames = names.filter((n) => specs[n].group === CSS_GROUP);
  if (!sameSet(cssNames, [...(lock.css ?? [])].sort())) {
    errors.push('lock css names do not match the specs in group css');
  }
  if (sha256(moduleText) !== lock.module.sha256) {
    errors.push(`generated module ${MODULE_PATH} does not match the lock; do not edit it by hand`);
  }

  const seen = new Set();
  let unmarked = 0;
  for (const [file, text] of Object.entries(css)) {
    const parsed = parseCssUris(text, tokens);
    for (const message of parsed.errors) errors.push(`${file}: ${message}`);
    for (const entry of parsed.uris) {
      if (entry.kind === 'bare') {
        unmarked += 1;
        if (tokens.requireMarkers) {
          errors.push(`${file}:${entry.line}: data:image/svg URI has no icon marker`);
        }
      }
      if (entry.kind !== 'icon') continue;
      if (!specs[entry.name]) {
        errors.push(`${file}:${entry.line}: marker names unknown icon ${entry.name}`);
        continue;
      }
      const key = uriKey(entry.name, entry.consumer, entry.theme);
      seen.add(key);
      if (!lock.uris[key]) errors.push(`${file}:${entry.line}: ${key} is not in the lock`);
      else if (lock.uris[key] !== sha256(entry.uri)) {
        errors.push(`${file}:${entry.line}: URI for ${key} differs from the lock`);
      }
    }
  }
  for (const key of Object.keys(lock.uris)) {
    if (!seen.has(key)) errors.push(`lock has ${key} but no CSS marker uses it`);
  }
  return { errors, unmarked };
};

const walk = async (dir, accept) => {
  const out = [];
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return out;
    throw error;
  }
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(path, accept)));
    else if (accept(entry.name)) out.push(path);
  }
  return out.sort();
};

/** Read specs, tokens, lock, the generated module and the stylesheets under a package root. */
const parseJson = (text, file) => {
  try {
    return JSON.parse(text);
  } catch (error) {
    throw new Error(`${file}: ${error.message}`);
  }
};

export const readTree = async (pkgRoot) => {
  const readJson = async (path) => parseJson(await readFile(join(pkgRoot, path), 'utf8'), path);
  const specs = {};
  for (const file of await walk(join(pkgRoot, 'icons/specs'), (n) => n.endsWith('.json'))) {
    const rel = relative(join(pkgRoot, 'icons/specs'), file).split('/');
    const name = rel.at(-1).slice(0, -'.json'.length);
    if (specs[name]) throw new Error(`duplicate icon name ${name}`);
    specs[name] = {
      group: rel[0],
      spec: parseJson(await readFile(file, 'utf8'), relative(pkgRoot, file)),
    };
  }
  const css = {};
  for (const file of await walk(join(pkgRoot, 'src/styles'), (n) => n.endsWith('.css'))) {
    css[relative(pkgRoot, file)] = await readFile(file, 'utf8');
  }
  return {
    tokens: await readJson('icons/tokens.json'),
    lock: await readJson('icons/icons.lock.json'),
    specs,
    moduleText: await readFile(join(pkgRoot, MODULE_PATH), 'utf8'),
    css,
  };
};

const hexToRgb = (hex) => [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16));

/** The three palette roles closest to a colour that is not in the palette. */
const nearestRoles = (palette, hex) => {
  const [r, g, b] = hexToRgb(hex);
  return Object.entries(palette)
    .map(([role, value]) => {
      const [pr, pg, pb] = hexToRgb(value);
      return [role, (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2];
    })
    .sort((a, b2) => a[1] - b2[1])
    .slice(0, 3)
    .map(([role]) => role);
};

/** Palette roles must not share a hex, or a colour could not be traced back to its role. */
export const validateTokens = (tokens) => {
  const errors = [];
  const owner = {};
  for (const [role, hex] of Object.entries(tokens.palette)) {
    if (owner[hex]) errors.push(`palette roles ${owner[hex]} and ${role} share ${hex}`);
    owner[hex] = role;
  }
  return errors;
};

const paintColors = (spec) => (spec.paint ?? []).map((layer) => layer.color);

/**
 * House rules applied to one spec on top of gridsmith's lint. Returns `{ rule, target, message }`.
 * `approved` lists the gridsmith rule ids this name may waive; `constraint` is its test constraint.
 */
export const lintSpecRules = ({ name, spec, tokens, approved = [], constraint = null }) => {
  const out = [];
  const add = (rule, target, message) => out.push({ rule, target, message });
  const hexes = new Set(Object.values(tokens.palette));

  (spec.paint ?? []).forEach((layer, index) => {
    const target = `paint[${index}]`;
    if (!hexes.has(layer.color)) {
      const near = nearestRoles(tokens.palette, layer.color ?? '#000000').join(', ');
      add('palette', target, `${layer.color} is not a palette colour (closest roles: ${near})`);
    }
    if (layer.stroke !== undefined) {
      if (!tokens.strokeWidths.includes(layer.width)) {
        add(
          'stroke_scale',
          target,
          `width ${layer.width} is not one of ${tokens.strokeWidths.join(', ')}`,
        );
      }
      const { cap, join } = tokens.stroke ?? {};
      if (cap !== undefined && (layer.cap ?? 'round') !== cap) {
        add('stroke_style', target, `cap ${layer.cap ?? 'round'} must be ${cap}`);
      }
      if (join !== undefined && (layer.join ?? 'round') !== join) {
        add('stroke_style', target, `join ${layer.join ?? 'round'} must be ${join}`);
      }
    }
  });

  const step = spec.grid?.step ?? 0.5;
  if (step === 0.1) add('grid_step', 'grid.step', 'step 0.1 is not allowed');
  else if (step === 0.25 && !(tokens.fineGrid ?? []).includes(name)) {
    add('grid_step', 'grid.step', 'step 0.25 is reserved for the names in tokens.json fineGrid');
  }

  const colors = paintColors(spec);
  const paper = tokens.palette.paper;
  const firstInk = colors.findIndex((c) => c !== paper);
  if (!constraint?.paperOverlay && firstInk >= 0 && colors.slice(firstInk).includes(paper)) {
    add(
      'paper_overlay',
      `paint[${colors.lastIndexOf(paper)}]`,
      'cut holes with subtract, not a paper layer on top',
    );
  }

  for (const exception of spec.exceptions ?? []) {
    if (!approved.includes(exception.rule)) {
      add('exception', exception.target ?? '', `exception for ${exception.rule} is not approved`);
    }
  }
  return out;
};

/** Gap samples are 1/8 unit apart, so a true gap can read one sample short. */
const GAP_RESOLUTION = 0.125;

/** Ink box and class limits: longest axis in the class range, centre within the offset. */
export const classViolations = ({ name, group, metrics, tokens }) => {
  const compact = (tokens.opticalClass.compact.names ?? []).includes(name);
  const cls = compact ? tokens.opticalClass.compact : tokens.opticalClass.standard;
  const [low, high] = cls.longestAxis;
  const out = [];
  const longest = Math.max(metrics.w, metrics.h);
  if (metrics.bleed > 0.05) out.push(`ink bleeds past the canvas by ${metrics.bleed}`);
  if (longest < low || longest > high) {
    out.push(
      `longest axis ${longest} is outside ${low}-${high} (${compact ? 'compact' : 'standard'})`,
    );
  }
  const off = Math.max(Math.abs(metrics.cx - 12), Math.abs(metrics.cy - 12));
  if (off > cls.centerOffset)
    out.push(`centre is off by ${off.toFixed(2)} (limit ${cls.centerOffset})`);
  if (group !== CSS_GROUP && metrics.gap !== null && metrics.gap + GAP_RESOLUTION < tokens.minGap) {
    out.push(`closest gap ${metrics.gap} is below ${tokens.minGap}`);
  }
  return out;
};

/** A test constraint: required fill/stroke roles per name, path count, paper overlay. */
export const constraintViolations = ({ constraint, segments, tokens }) => {
  const out = [];
  for (const need of constraint.requires ?? []) {
    const hex = tokens.palette[need.role];
    const hit = segments.some((s) => (need.paint === 'fill' ? s.fill === hex : s.stroke === hex));
    if (!hit) out.push(`needs a ${need.paint} in role ${need.role}`);
  }
  if (constraint.pathCount !== undefined && segments.length !== constraint.pathCount) {
    out.push(`needs exactly ${constraint.pathCount} paths, has ${segments.length}`);
  }
  return out;
};
