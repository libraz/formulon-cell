import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

import {
  checkTree,
  dataUriFor,
  emitModule,
  normalizeSpec,
  parseCssUris,
  readTree,
  rewriteCssUris,
  sha256,
  specHash,
  toIconSegments,
  uriKey,
  yarnLockGridsmithCommit,
} from '../../../scripts/icons/emit.mjs';

const PKG_ROOT = join(import.meta.dirname, '../../..');

const tokens = {
  palette: { ink: '#1f1f1f', paper: '#ffffff', mute: '#f3f2f1', accent: '#107c41' },
  themes: {
    light: { ink: '#1f1f1f', paper: '#ffffff', mute: '#f3f2f1' },
    ink: { ink: '#f3f2f1', paper: '#323130', mute: '#3b3a39' },
  },
  cssConsumers: { menu: {} },
  requireMarkers: true,
};

const spec = { version: 1, mode: 'icon', paint: [{ fill: 'a', color: '#107c41' }], shapes: [] };
const segments = [
  {
    d: 'M1 1L5 5',
    stroke: '#1f1f1f',
    strokeWidth: 1,
    strokeLinecap: 'round',
    strokeLinejoin: 'round',
  },
  { d: 'M2 2L6 2L6 6Z', fill: '#107c41', fillRule: 'evenodd' },
];
const defs = toIconSegments(segments);

/** A self-consistent tree to mutate one fact at a time. */
const fixture = () => {
  const specs = { sample: { group: 'format', spec }, menuSample: { group: 'css', spec } };
  const icons = { sample: defs };
  const moduleText = emitModule({ palette: tokens.palette, icons });
  const css = `.a { background-image: ${dataUriFor(segments, tokens, 'light')} /* icon:menuSample @menu */; }\n`;
  const uris = {
    [uriKey('menuSample', 'menu', 'light')]: sha256(dataUriFor(segments, tokens, 'light')),
  };
  const lock = {
    gridsmith: { commit: 'abc' },
    specs: {
      sample: { group: 'format', sha256: specHash(spec) },
      menuSample: { group: 'css', sha256: specHash(spec) },
    },
    module: { sha256: sha256(moduleText) },
    css: ['menuSample'],
    uris,
  };
  return { tokens, lock, specs, moduleText, css: { 'menu.css': css } };
};

describe('spec hashing', () => {
  it('ignores key order and formatting', () => {
    const a = { b: 1, a: { y: [1, 2], x: 2 } };
    const b = { a: { x: 2, y: [1, 2] }, b: 1 };
    expect(normalizeSpec(a)).toBe(normalizeSpec(b));
    expect(specHash(a)).toBe(specHash(b));
  });

  it('changes when a value changes', () => {
    expect(specHash({ a: 1 })).not.toBe(specHash({ a: 2 }));
  });
});

describe('generated module', () => {
  it('emits an empty registry with a never union', () => {
    const text = emitModule({ palette: tokens.palette, icons: {} });
    expect(text).toContain('export type RibbonIconName = never;');
    expect(text).toContain('export const RIBBON_ICONS');
    expect(text).toMatch(/^\/\/ Generated by scripts\/icons\/generate\.mjs/);
  });

  it('emits sorted names and stroke or fill segments without transforms', () => {
    const text = emitModule({ palette: tokens.palette, icons: { zed: defs, add: defs } });
    expect(text.indexOf("'add'")).toBeLessThan(text.indexOf("'zed'"));
    expect(text).toContain("strokeWidth: '1'");
    expect(text).toContain("fillRule: 'evenodd'");
    expect(text).not.toContain('transform');
  });

  it('keeps fill segments free of stroke fields and stroke segments free of fill', () => {
    const [stroked, filled] = defs;
    expect(stroked.fill).toBeUndefined();
    expect(filled.stroke).toBeUndefined();
    expect(stroked.strokeWidth).toBe('1');
  });
});

describe('css data URIs', () => {
  it('escapes only the characters a url() value cannot carry', () => {
    const uri = dataUriFor(segments, tokens, 'light');
    expect(uri.startsWith('url("data:image/svg+xml,')).toBe(true);
    expect(uri).toContain("viewBox='0 0 24 24'");
    expect(uri).toContain('%23107c41');
    expect(uri).not.toMatch(/[<>#]/);
  });

  it('bakes the theme values into themed roles only', () => {
    const themed = [
      { d: 'M0 0L1 1', stroke: '#1f1f1f', strokeWidth: 1 },
      { d: 'M0 0L1 1', stroke: '#107c41', strokeWidth: 1 },
    ];
    const ink = dataUriFor(themed, tokens, 'ink');
    expect(ink).toContain('%23f3f2f1');
    expect(ink).toContain('%23107c41');
    expect(ink).not.toContain('%231f1f1f');
  });
});

describe('css markers', () => {
  const uri = dataUriFor(segments, tokens, 'light');

  it('parses an icon marker, its consumer and theme', () => {
    const css = `a { background-image: ${uri} /* icon:copy @menu theme=ink */; }`;
    const { uris, errors } = parseCssUris(css, tokens);
    expect(errors).toEqual([]);
    expect(uris).toHaveLength(1);
    expect(uris[0]).toMatchObject({ kind: 'icon', name: 'copy', consumer: 'menu', theme: 'ink' });
  });

  it('accepts an exempt marker and reports a bare URI', () => {
    const css = `a { x: ${uri} /* icon-exempt:cursor */; }\nb { y: ${uri}; }`;
    const { uris } = parseCssUris(css, tokens);
    expect(uris.map((u) => u.kind)).toEqual(['exempt', 'bare']);
  });

  it('rejects a bad grammar, an unknown consumer and a mask context', () => {
    const noSemi = parseCssUris(`a { b: ${uri} /* icon:copy @menu */ }`, tokens);
    expect(noSemi.errors.join('\n')).toMatch(/copy/);
    const unknown = parseCssUris(`a { b: ${uri} /* icon:copy @nowhere */; }`, tokens);
    expect(unknown.errors.join('\n')).toMatch(/nowhere/);
    const mask = parseCssUris(`a { -webkit-mask: ${uri} /* icon:copy @menu */; }`, tokens);
    expect(mask.errors.join('\n')).toMatch(/mask/);
  });

  it('rewrites a marked URI in place and leaves other text alone', () => {
    const css = `a { b: url("data:image/svg+xml,stale") /* icon:copy @menu */; }\n/* keep */\n`;
    const out = rewriteCssUris(css, tokens, () => uri);
    expect(out).toBe(`a { b: ${uri} /* icon:copy @menu */; }\n/* keep */\n`);
    expect(rewriteCssUris(out, tokens, () => uri)).toBe(out);
  });
});

describe('staleness check', () => {
  it('passes a consistent tree', () => {
    expect(checkTree(fixture()).errors).toEqual([]);
  });

  it('names a hand-edited spec', () => {
    const tree = fixture();
    tree.specs.sample = { group: 'format', spec: { ...spec, concept: 'edited' } };
    expect(checkTree(tree).errors.join('\n')).toMatch(/sample/);
  });

  it('flags a spec missing from the lock and a lock entry without a spec', () => {
    const tree = fixture();
    tree.specs.extra = { group: 'format', spec };
    delete tree.specs.sample;
    const text = checkTree(tree).errors.join('\n');
    expect(text).toMatch(/extra/);
    expect(text).toMatch(/sample/);
  });

  it('flags a hand-edited module', () => {
    const tree = fixture();
    tree.moduleText = `${tree.moduleText}// edit\n`;
    expect(checkTree(tree).errors.join('\n')).toMatch(/module/i);
  });

  it('flags a hand-edited CSS URI by name', () => {
    const tree = fixture();
    tree.css['menu.css'] = tree.css['menu.css'].replace('%23107c41', '%23ff0000');
    expect(checkTree(tree).errors.join('\n')).toMatch(/menuSample/);
  });

  it('flags a marker inside a mask', () => {
    const tree = fixture();
    tree.css['menu.css'] = tree.css['menu.css'].replace('background-image', '-webkit-mask');
    expect(checkTree(tree).errors.join('\n')).toMatch(/mask/);
  });

  it('counts unmarked URIs as a note until markers are required', () => {
    const tree = fixture();
    tree.css['bare.css'] = `a { b: ${dataUriFor(segments, tokens, 'light')}; }`;
    tree.tokens = { ...tokens, requireMarkers: false };
    const lenient = checkTree(tree);
    expect(lenient.errors).toEqual([]);
    expect(lenient.unmarked).toBe(1);
    expect(checkTree({ ...tree, tokens }).errors.join('\n')).toMatch(/bare\.css/);
  });
});

describe('yarn.lock pin', () => {
  it('reads the commit from the gridsmith resolution', () => {
    const lock = [
      '"@libraz/gridsmith@github:libraz/gridsmith#commit=aaaa":',
      '  version: 0.1.0',
      `  resolution: "@libraz/gridsmith@https://github.com/libraz/gridsmith.git#commit=${'a'.repeat(40)}"`,
    ].join('\n');
    expect(yarnLockGridsmithCommit(lock)).toBe('a'.repeat(40));
    expect(yarnLockGridsmithCommit('nothing')).toBeNull();
  });
});

describe('committed tree', () => {
  it('has specs, module and CSS URIs that match the lock', async () => {
    const tree = await readTree(PKG_ROOT);
    const result = checkTree(tree);
    expect(result.errors).toEqual([]);
  });
});
