describe('pivot layouts match the desktop app', () => {
  it.each(LAYOUTS)('%s', async (file, grid) => {
    const wb = await loadFixture(file);
    try {
      expect(pivotGrid(wb)).toEqual(grid);
    } finally {
      wb.dispose();
    }
  });

  it('nests values under each item with "<item> <caption>" subtotals (ja_d8)', async () => {
    const wb = await loadFixture('ja_d8_two_rows_values_rows.xlsx');
    try {
      const grid = pivotGrid(wb);
      const labels = Object.entries(grid)
        .filter(([ref]) => ref.startsWith('A') && ref !== 'A3')
        .map(([, v]) => v);
      expect(labels.slice(0, 6)).toEqual([
        'East',
        'A',
        'Sum of Amt',
        'Sum of Qty',
        'East Sum of Amt',
        'East Sum of Qty',
      ]);
      expect(labels.slice(-2)).toEqual(['全体の Sum of Amt', '全体の Sum of Qty']);
      expect([grid.B8, grid.B9, grid.B28, grid.B29]).toEqual([500, 5, 1500, 15]);
    } finally {
      wb.dispose();
    }
  });

  it('heads subtotal columns "<item> <caption>" (ja_d9)', async () => {
    const wb = await loadFixture('ja_d9_two_cols_values_cols.xlsx');
    try {
      const grid = pivotGrid(wb);
      expect([grid.C4, grid.D4, grid.I4, grid.Q4, grid.R4]).toEqual([
        'East Sum of Amt',
        'East Sum of Qty',
        'North Sum of Amt',
        '全体の Sum of Amt',
        '全体の Sum of Qty',
      ]);
      expect([grid.Q7, grid.R7]).toEqual([1500, 15]);
    } finally {
      wb.dispose();
    }
  });
});
